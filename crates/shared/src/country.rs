/// Currency in use in `country` (alpha-2, any case).
pub fn currency_for_country(country: &str) -> Option<&'static str> {
    let cc = country.trim().to_ascii_uppercase();
    COUNTRY_CURRENCIES
        .binary_search_by(|(c, _)| (*c).cmp(cc.as_str()))
        .ok()
        .map(|i| COUNTRY_CURRENCIES[i].1)
}

/// Canonical upper-case code when `country` is a known alpha-2 code.
pub fn normalize_country(country: &str) -> Option<&'static str> {
    let cc = country.trim().to_ascii_uppercase();
    COUNTRY_CURRENCIES
        .binary_search_by(|(c, _)| (*c).cmp(cc.as_str()))
        .ok()
        .map(|i| COUNTRY_CURRENCIES[i].0)
}

/// Countries whose receipts print the month first (`10/09` = October 9).
pub fn month_first_dates(country: &str) -> bool {
    // ponytail: US-style only; extend if another month-first country shows up.
    matches!(country, "US" | "PH")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_for_binary_search() {
        assert!(COUNTRY_CURRENCIES.windows(2).all(|w| w[0].0 < w[1].0));
    }

    #[test]
    fn lookups() {
        assert_eq!(currency_for_country("uy"), Some("UYU"));
        assert_eq!(currency_for_country("AR"), Some("ARS"));
        assert_eq!(currency_for_country("ES"), Some("EUR"));
        assert_eq!(currency_for_country("EC"), Some("USD"));
        assert_eq!(currency_for_country("XX"), None);
        assert_eq!(normalize_country(" uy "), Some("UY"));
        assert_eq!(normalize_country("Uruguay"), None);
    }
}
